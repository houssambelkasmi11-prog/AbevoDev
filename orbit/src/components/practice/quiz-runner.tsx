"use client";

import { ArrowLeft, BookOpen, Check, Timer, X } from "lucide-react";
import Link from "next/link";
import { useEffect, useRef, useState, useTransition } from "react";
import { Markdown } from "@/components/app/markdown";
import { Ring } from "@/components/app/viz";
import { Button } from "@/components/ui/button";
import { Badge, Textarea } from "@/components/ui/field";
import { useToast } from "@/components/ui/toast";
import type { QuizAttemptRow, QuizRow } from "@/lib/types";
import { cn, formatDate } from "@/lib/utils";
import { submitQuizAttempt } from "@/server/actions/practice";

export function QuizRunner({ quiz, hasProvider, previous, onExit }: { quiz: QuizRow; hasProvider: boolean; previous: QuizAttemptRow[]; onExit: () => void }) {
  const toast = useToast();
  const [answers, setAnswers] = useState<Record<string, string>>({});
  const [selfScores, setSelfScores] = useState<Record<string, number>>({});
  const [result, setResult] = useState<QuizAttemptRow | null>(null);
  const [aiGrade, setAiGrade] = useState(hasProvider);
  const [elapsed, setElapsed] = useState(0);
  const [pending, start] = useTransition();
  const startedAt = useRef(Date.now());
  const limit = quiz.time_limit_minutes ? quiz.time_limit_minutes * 60 : null;

  useEffect(() => {
    if (result) return;
    const t = setInterval(() => setElapsed(Math.round((Date.now() - startedAt.current) / 1000)), 1000);
    return () => clearInterval(t);
  }, [result]);

  const submit = () =>
    start(async () => {
      const r = await submitQuizAttempt(
        quiz.id,
        quiz.questions.map((q) => ({ questionId: q.id, response: answers[q.id] ?? "", selfScore: q.type === "mcq" ? null : selfScores[q.id] ?? null })),
        (Date.now() - startedAt.current) / 1000,
        aiGrade,
      );
      if (r.ok) {
        setResult(r.data);
        window.scrollTo({ top: 0, behavior: "smooth" });
      } else toast.error(r.error);
    });

  // Auto-submit when an exam's time runs out.
  useEffect(() => {
    if (limit && elapsed >= limit && !result && !pending) submit();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [elapsed, limit]);

  const remaining = limit ? Math.max(0, limit - elapsed) : null;
  const answered = quiz.questions.filter((q) => (answers[q.id] ?? "").trim()).length;

  return (
    <div className="mx-auto max-w-3xl">
      <div className="flex items-center justify-between gap-3">
        <button onClick={onExit} className="flex items-center gap-1.5 rounded-md px-1.5 py-1 text-[12.5px] text-ink-2 hover:bg-soft hover:text-ink">
          <ArrowLeft className="h-3.5 w-3.5" /> All quizzes
        </button>
        {!result ? (
          <span className={cn("flex items-center gap-2 font-mono text-[12px]", remaining !== null && remaining < 60 ? "text-danger" : "text-ink-2")} aria-live="polite">
            <Timer className="h-3.5 w-3.5" />
            {remaining !== null ? `${Math.floor(remaining / 60)}:${String(remaining % 60).padStart(2, "0")} left` : `${Math.floor(elapsed / 60)}:${String(elapsed % 60).padStart(2, "0")}`}
          </span>
        ) : null}
      </div>
      <h2 className="mt-4 font-display text-[clamp(1.6rem,3vw,2.3rem)] font-bold tracking-[-0.03em]">{quiz.title}</h2>
      <p className="mt-1 text-[12.5px] text-ink-2">
        {quiz.questions.length} questions {quiz.exam ? "· practice exam" : ""} {quiz.model ? `· generated by ${quiz.model}` : ""} {previous.length ? `· ${previous.length} previous attempt${previous.length > 1 ? "s" : ""}` : ""}
      </p>

      {result ? (
        <div className="mt-6 flex items-center gap-5 rounded-2xl border border-line bg-surface p-5 shadow-soft">
          <Ring value={result.score} size={84}>
            <span className="font-display text-xl font-bold">{Math.round(result.score * 100)}</span>
          </Ring>
          <div>
            <p className="label text-ink-3">Result</p>
            <p className="mt-1 text-[14px]">
              {result.answers.filter((a) => a.correct).length} of {result.answers.length} correct · {Math.round(result.duration_seconds / 60)} min
            </p>
            <p className="mt-1 text-[12.5px] text-ink-2">Review the explanations below — especially the ones you missed.</p>
          </div>
        </div>
      ) : null}

      <ol className="mt-8 space-y-5">
        {quiz.questions.map((q, i) => {
          const a = result?.answers.find((x) => x.questionId === q.id);
          return (
            <li key={q.id} className={cn("rounded-2xl border bg-surface p-5 shadow-soft", a ? (a.correct ? "border-ok/50" : a.correct === false ? "border-danger/50" : "border-line") : "border-line")}>
              <div className="flex items-center gap-2">
                <span className="font-mono text-[11px] text-ink-3">{String(i + 1).padStart(2, "0")}</span>
                <Badge>{q.type === "mcq" ? "Multiple choice" : q.type === "short" ? "Short answer" : "Open"}</Badge>
                {a ? a.correct ? <Check className="h-4 w-4 text-ok" /> : a.correct === false ? <X className="h-4 w-4 text-danger" /> : null : null}
              </div>
              <div className="mt-3 text-[15px] font-medium">
                <Markdown text={q.prompt} />
              </div>

              {q.type === "mcq" ? (
                <fieldset className="mt-4 grid gap-2" disabled={!!result}>
                  <legend className="sr-only">Options</legend>
                  {q.options.map((o) => {
                    const chosen = answers[q.id] === o;
                    const correct = result && o === q.answer;
                    return (
                      <label
                        key={o}
                        className={cn(
                          "flex cursor-pointer items-start gap-3 rounded-xl border px-4 py-3 text-[13.5px] transition-colors",
                          chosen ? "border-ink bg-soft" : "border-line hover:border-ink-2",
                          correct && "border-ok bg-[color-mix(in_oklab,var(--ok)_10%,transparent)]",
                          result && chosen && !correct && "border-danger",
                        )}
                      >
                        <input type="radio" name={q.id} checked={chosen} onChange={() => setAnswers((x) => ({ ...x, [q.id]: o }))} className="mt-1 accent-[var(--ink)]" />
                        <Markdown text={o} />
                      </label>
                    );
                  })}
                </fieldset>
              ) : (
                <div className="mt-4">
                  <Textarea
                    value={answers[q.id] ?? ""}
                    onChange={(e) => setAnswers((x) => ({ ...x, [q.id]: e.target.value }))}
                    disabled={!!result}
                    placeholder="Your answer…"
                    className={q.type === "open" ? "min-h-[140px]" : "min-h-[64px]"}
                    aria-label={`Answer to question ${i + 1}`}
                  />
                  {!result && !aiGrade ? (
                    <label className="mt-2 flex items-center gap-3 text-[12px] text-ink-2">
                      Self-assess after checking the answer:
                      <input type="range" min={0} max={1} step={0.25} value={selfScores[q.id] ?? 0} onChange={(e) => setSelfScores((s) => ({ ...s, [q.id]: Number(e.target.value) }))} className="accent-[var(--ink)]" />
                      <span className="font-mono">{Math.round((selfScores[q.id] ?? 0) * 100)}%</span>
                    </label>
                  ) : null}
                </div>
              )}

              {result ? (
                <div className="mt-4 space-y-2 border-t border-line pt-4 text-[13px]">
                  {q.type !== "mcq" ? (
                    <div>
                      <p className="label text-ink-3">{q.type === "open" ? "Key points" : "Model answer"}</p>
                      <Markdown text={q.answer} />
                    </div>
                  ) : null}
                  {a?.feedback ? (
                    <div>
                      <p className="label text-ink-3">Feedback · {Math.round((a.score ?? 0) * 100)}%</p>
                      <p className="text-ink-2">{a.feedback}</p>
                    </div>
                  ) : null}
                  {q.explanation ? (
                    <div>
                      <p className="label text-ink-3">Why</p>
                      <Markdown text={q.explanation} className="text-ink-2" />
                    </div>
                  ) : null}
                  {q.source ? (
                    <Link
                      href={q.source.type === "note" ? `/app/notes/${q.source.id}` : `/app/lessons/${q.source.id}${q.source.page ? `?page=${q.source.page}` : ""}`}
                      className="inline-flex items-center gap-1.5 text-[12px] text-ink-2 underline-offset-2 hover:text-ink hover:underline"
                      title={q.source.excerpt ?? undefined}
                    >
                      <BookOpen className="h-3 w-3" /> Source: {q.source.title}
                      {q.source.page ? ` · p.${q.source.page}` : ""}
                    </Link>
                  ) : null}
                </div>
              ) : null}
            </li>
          );
        })}
      </ol>

      {!result ? (
        <div className="sticky bottom-20 mt-8 flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-line bg-surface/95 p-4 shadow-lift backdrop-blur lg:bottom-6">
          <span className="text-[12.5px] text-ink-2">
            {answered} / {quiz.questions.length} answered
          </span>
          <div className="flex items-center gap-3">
            {quiz.questions.some((q) => q.type !== "mcq") ? (
              <label className={cn("flex items-center gap-2 text-[12.5px]", !hasProvider && "opacity-50")}>
                <input type="checkbox" checked={aiGrade} disabled={!hasProvider} onChange={(e) => setAiGrade(e.target.checked)} className="accent-[var(--ink)]" />
                AI-grade written answers
              </label>
            ) : null}
            <Button onClick={submit} loading={pending}>
              Submit
            </Button>
          </div>
        </div>
      ) : (
        <div className="mt-8 flex gap-2">
          <Button
            onClick={() => {
              setResult(null);
              setAnswers({});
              setSelfScores({});
              startedAt.current = Date.now();
              setElapsed(0);
            }}
          >
            Try again
          </Button>
          <Button variant="outline" onClick={onExit}>
            Done
          </Button>
        </div>
      )}

      {previous.length && !result ? (
        <p className="mt-6 text-[12px] text-ink-3">
          Previous: {previous.slice(-5).map((p) => `${Math.round(p.score * 100)}% (${formatDate(p.created_at)})`).join(" · ")}
        </p>
      ) : null}
    </div>
  );
}
