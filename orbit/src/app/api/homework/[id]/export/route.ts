import { NextResponse, type NextRequest } from "next/server";
import { getRepoOrNull } from "@/lib/auth/session";
import { toDocx, toMarkdown, toPdf, toPlainText, type ExportSection } from "@/lib/export";

export const dynamic = "force-dynamic";

const TYPES = {
  md: "text/markdown; charset=utf-8",
  txt: "text/plain; charset=utf-8",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  pdf: "application/pdf",
} as const;

export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const ctx = await getRepoOrNull();
  if (!ctx) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  const { id } = await params;
  const a = await ctx.repo.get("assignments", id);
  if (!a) return NextResponse.json({ error: "Not found" }, { status: 404 });
  const format = (req.nextUrl.searchParams.get("format") ?? "md") as keyof typeof TYPES;
  if (!(format in TYPES)) return NextResponse.json({ error: "Unsupported format" }, { status: 400 });
  const include = req.nextUrl.searchParams.get("include") ?? "work";

  const sections: ExportSection[] = [];
  if (include === "work" || include === "both") {
    sections.push({ label: "Your work", note: "Written by the student.", markdown: a.student_work.trim() || "_(empty)_" });
  }
  if ((include === "draft" || include === "both") && a.ai_output) {
    sections.push({
      label: "AI-generated draft",
      note: `Generated by ${a.ai_output_model ?? "an AI model"} in ORBIT as a study aid. Not the student's own work — review, verify and rewrite before any submission.`,
      markdown: a.ai_output,
    });
  }
  if (include === "both" && a.review.length) {
    sections.push({
      label: "AI review notes",
      note: "Suggestions only — the student's work above was not changed.",
      markdown: a.review.map((f) => `- **${f.category} (${f.severity})**: ${f.comment}${f.suggestion ? ` — Suggestion: ${f.suggestion}` : ""}`).join("\n"),
    });
  }
  if (!sections.length) return NextResponse.json({ error: "Nothing to export yet." }, { status: 400 });

  const safeName = a.title.replace(/[^\w\- ]+/g, "").trim().slice(0, 80) || "assignment";
  let body: Uint8Array;
  if (format === "md") body = new TextEncoder().encode(toMarkdown(a.title, sections));
  else if (format === "txt") body = new TextEncoder().encode(toPlainText(toMarkdown(a.title, sections)));
  else if (format === "docx") body = await toDocx(a.title, sections);
  else body = await toPdf(a.title, sections);

  await ctx.repo.update("assignments", id, { stages: { ...a.stages, export: "done" } }).catch(() => undefined);

  return new NextResponse(new Uint8Array(body), {
    headers: {
      "Content-Type": TYPES[format],
      "Content-Disposition": `attachment; filename="${safeName}.${format}"`,
      "Cache-Control": "no-store",
    },
  });
}
